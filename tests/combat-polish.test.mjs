import test from 'node:test';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';

// QA_COMBAT_ROOT permits the same regression to be run against the unchanged
// uploaded source. Normal npm test always imports this project's implementation.
const root=process.env.QA_COMBAT_ROOT?pathToFileURL(process.env.QA_COMBAT_ROOT.replace(/\/$/,'')+'/'):new URL('../',import.meta.url);
const E=await import(new URL('src/engine.js',root));
const {validateSave,encodeSave,decodeSave}=await import(new URL('src/storage.js',root));
const {ENEMIES,CATALOG}=await import(new URL('src/content.js',root));

function scene(type='combat',seed=22,floor=30){
 let s=E.newGame(seed);s.floor=floor;s.player.level=20;s.player.hp=E.stats(s).maxHp;
 s.phase='route';s.fate=[3,4];s.roomIndex=0;
 s.route=[type,'combat','rest','combat','gold',floor%5===0?'boss':'elite'].map((type,i)=>({id:`f${floor}r${i}`,type,done:false,quality:0}));
 s=E.transition(s,{type:'enter'});assert(validateSave(s));return s;
}
const reload=s=>{assert(validateSave(s));const loaded=decodeSave(encodeSave(s));assert.deepEqual(loaded,s);return loaded;};

test('regional sequence enemies rebuild real shields in ordinary rooms, with no free opening shield',()=>{
 const s=scene();assert.equal(s.enemy.name,'断层探灯者');assert.equal(s.enemy.mechanic,'sequence');assert.equal(s.enemy.shield,0);
 s.rng=17;const after=E.transition(s,{type:'roll'});
 assert.deepEqual(after.lastRoll.values,[1,2,2,1,1,2]);assert(after.player.hp>0);assert(!after.lastRoll.killed);
 assert(after.lastRoll.mechanics.includes('刻点不足 · 重筑 3% 护盾'));
 assert(after.enemy.shield>0,'a displayed shield rebuild must add a usable shield');
 assert.equal(after.enemy.shield,Math.ceil(after.enemy.maxHp*.03));
 assert(after.enemy.shield<=after.enemy.maxShield);reload(after);
});

test('existing V5 zero-capacity regional encounters recover on the next roll and replay identically',()=>{
 const original=scene();original.enemy.maxShield=0;original.enemy.shield=0;original.rng=17;
 const restored=reload(original),beforeRng=restored.rng;
 const after=E.transition(restored,{type:'roll'}),direct=E.transition(original,{type:'roll'});
 assert.deepEqual(after,direct);assert.notEqual(after.rng,beforeRng);
 assert(after.enemy.shield>0,'loading the current V5 encounter must not retain the broken capacity');
 assert.equal(after.enemy.name,original.enemy.name);assert.equal(after.enemy.turns,1);reload(after);
});

test('regional rebuild capacity is present across eras and remains bounded during repeated low-diversity rolls',()=>{
 const templates=ENEMIES.filter(e=>e.mechanic==='sequence'&&!e.roomType);
 assert.equal(templates.length,5);
 for(const template of templates){
  let generated=null;
  for(let seed=1;seed<=1000&&!generated;seed++){
   const s=scene('combat',seed,template.minFloor);
   if(s.enemy.name===template.name)generated=s;
  }
  assert(generated,template.name+' must be generated by an ordinary combat room');
  assert(generated.enemy.maxShield>0,template.name+' rebuild capacity');
  assert.equal(generated.enemy.shield,0,template.name+' must keep its original opening state');
 }
 let s=scene();s.player.level=1;s.player.hp=E.stats(s).maxHp;s.ward=1e15;
 for(let n=0;n<20;n++){
  s=E.transition(s,{type:'roll'});assert.equal(s.phase,'combat');assert(s.enemy.shield<=s.enemy.maxShield);reload(s);
 }
 assert.equal(s.enemy.shield,s.enemy.maxShield,'rebuilding reaches its authored cap instead of growing forever');
});

test('rest heals and fills a weak shield while retaining a stronger existing shield',()=>{
 for(const fraction of [0,.1,.75,2]){
  const s=scene('rest');s.player.hp=1;s.ward=Math.round(E.stats(s).maxHp*fraction);
  const after=E.transition(reload(s),{type:'rest'});
  assert.equal(after.player.hp,E.stats(after).maxHp);
  assert(after.ward>=s.ward,'recovery must not destroy an existing shield');
  assert(after.ward>=Math.round(E.stats(after).maxHp*.25));
  assert.equal(after.rng,s.rng,'rest must not draw RNG');
  assert.equal(after.roomUsed,true);assert.strictEqual(E.transition(after,{type:'rest'}),after);reload(after);
 }
});

function defensiveScene(){
 const s=scene('combat',22,80);
 for(const item of s.player.items){
  const entry=CATALOG[item.slot].find(e=>e.id===`${item.slot}-0-0-0`);
  Object.assign(item,{catalogId:entry.id,name:entry.name,profile:entry.profile,theme:entry.theme});
 }
 s.player.hp=E.stats(s).maxHp;s.ward=0;
 s.enemy={name:'合成预告守卫',note:'Isolated forecast fixture.',label:'固定普通反击',trait:'steady',type:'combat',maxHp:1e9,hp:1e9,maxShield:0,shield:0,attack:100,turns:0,stage:1,combatRules:4};
 assert.equal(E.stats(s).dodge,0);assert.equal(E.stats(s).pairWard,0);assert(validateSave(s));return s;
}
function forecastRolls(s,seeds=99){
 const before=structuredClone(s),forecast=E.enemyIntent(s),observed=new Set();
 assert.deepEqual(s,before,'forecast must not alter state or advance RNG');
 for(let rng=1;rng<=seeds;rng++){
  const start=structuredClone(s);start.rng=rng;
  const after=E.transition(start,{type:'roll'}),loss=after.lastRoll.retaliation;observed.add(loss);
  assert(!after.lastRoll.killed);assert(loss>=forecast.minDamage&&loss<=forecast.maxDamage);reload(after);
 }
 return {forecast,observed:[...observed].sort((a,b)=>a-b)};
}

test('counter preview applies the same mandatory V5 low-health reduction as the actual roll',()=>{
 const s=defensiveScene();s.player.talents.lastResolve=3;s.player.hp=Math.floor(E.stats(s).maxHp*.25);
 const {forecast,observed}=forecastRolls(s);
 assert.deepEqual(observed,[77]);assert.equal(forecast.minDamage,77);assert.equal(forecast.maxDamage,77);
});

test('small V5 critical/low-face wards no longer claim a possible zero-damage counter',()=>{
 for(const talent of ['critAegis','emberGuard']){
  const s=defensiveScene();s.player.talents[talent]=1;
  const {forecast,observed}=forecastRolls(s,200);
  assert.deepEqual(observed,[86,95],talent+' must exercise the active and inactive ward');
  assert.equal(forecast.minDamage,86);assert.equal(forecast.maxDamage,95);
 }
});

test('phase protection is forecast only for an actual possible phase change',()=>{
 const s=defensiveScene();s.player.talents.phaseShelter=3;Object.assign(s.enemy,{type:'boss',stage:2,hp:5e8,maxShield:12e7});
 const {forecast,observed}=forecastRolls(s,20);
 assert.deepEqual(observed,[110]);assert.equal(forecast.minDamage,110);assert.equal(forecast.maxDamage,110);
 s.enemy.stage=1;s.enemy.hp=5e8+1;
 const crossing=forecastRolls(s,20);assert(crossing.forecast.minDamage>0);assert(crossing.observed[0]<110);
});

test('legacy odd-HP phase boundaries retain a conservative forecast with new phase protection',()=>{
 const s=defensiveScene();s.player.talents.phaseShelter=1;
 Object.assign(s.enemy,{type:'boss',trait:'rage',combatRules:2,maxHp:101,hp:100,stage:1,maxShield:20});
 const forecast=E.enemyIntent(s),after=E.transition(reload(s),{type:'roll'});
 assert.equal(after.enemy.hp,51);assert(after.lastRoll.phaseChanged);
 assert.equal(after.lastRoll.retaliation,87);assert.equal(forecast.minDamage,87);
 assert(after.lastRoll.retaliation<=forecast.maxDamage);reload(after);
});
